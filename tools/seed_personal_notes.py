def seed(vault: Path):
    written = 0
    for topic, kind, goal, criteria, entries in SCENARIOS:
        folder = ("学习" if kind == "learning" else "项目") + "/" + topic
        records = [("目标/" + goal + ".md", goal, "goal", date(2026, 9, 1), criteria)]
        previous = None
        for index, (title, content) in enumerate(entries):
            day = date(2026, 9, 3) + timedelta(days=index * 3)
            path = folder + "/" + day.isoformat() + "-" + title + ".md"
            if previous:
                content += "\n\n前一次记录：[[" + previous[:-3] + "]]。"
            records.append((path, title, kind, day, content))
            previous = path
        for relative, title, record_kind, day, content in records:
            text = f"---\ndate: {day}\ntype: {record_kind}\ntopic: {topic}\nsynthetic: true\ntags: [公开虚构, {topic}]\n---\n# {title}\n\n> 公开虚构演示记录，不对应真实个人经历。\n\n{content}\n"
            path = vault / relative
            if path.exists() and path.read_text(encoding="utf-8") != text:
                raise ValueError("文件已经被修改，停止覆盖：" + relative)
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            written += 1
    return written


